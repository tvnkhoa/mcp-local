const extract = (source: string, filePath: string) => extractGraphData({ repoId: "r", filePath, language: "csharp", source });
const sql = (out: ReturnType<typeof extract>) => out.symbols.filter((s) => s.kind.startsWith("sql_"));

test("release L3: the snapshot's tables, columns (owned ones join their table), keys, indexes, checks, FKs and sequence", () => {
  const out = extract(SNAPSHOT, "src/Migrations/AppDbContextModelSnapshot.cs");
  const tables = out.symbols.filter((s) => s.kind === "sql_table");
  assert.deepEqual(tables.map((t) => t.signature), [
    "conversations — table (5 columns, 1 checks) [EF AppDbContext: App.Domain.Conversation]",
    "notes — table (2 columns) [EF AppDbContext: App.Domain.Note]"
  ]);
  const cols = out.symbols.filter((s) => s.kind === "sql_column").map((s) => s.signature ?? "");
  assert.ok(cols.includes("conversations.id — column uuid (not null, primary key) [EF AppDbContext: App.Domain.Conversation.Id]"));
  assert.ok(cols.includes("conversations.channel — column character varying(32) (not null, max 32) [EF AppDbContext: App.Domain.Conversation.Channel]"));
  assert.ok(cols.includes("conversations.tenant_id — column integer [EF AppDbContext: App.Domain.Conversation.TenantId]"), "int? is nullable");
  assert.ok(cols.includes("conversations.tags — column text[] (not null) [EF AppDbContext: App.Domain.Conversation.Tags]"), "PrimitiveCollection is a column");
  assert.ok(cols.includes("conversations.handled_by — column character varying(16) [EF AppDbContext: App.Domain.Assignment.HandledBy]"), "owned column joins the owner table");
  assert.equal(cols.filter((c) => c.startsWith("conversations.id ")).length, 1, "the owned key repeats the owner's id: one column");
  const idx = out.symbols.filter((s) => s.kind === "sql_index").map((s) => s.signature);
  assert.deepEqual(idx, [
    "ix_conv_tenant_channel — unique index on conversations (tenant_id, channel) where tenant_id IS NOT NULL [EF AppDbContext: App.Domain.Conversation]",
    "ix_conv_channel_gin — index on conversations (channel) using gin [EF AppDbContext: App.Domain.Conversation]"
  ]);
  assert.ok(out.symbols.some((s) => s.kind === "sql_statement" && s.name === "constraint ck_conv_channel" && s.signature?.startsWith("check (channel IN ('sms','email'))")));
  assert.ok(out.symbols.some((s) => s.kind === "sql_sequence" && s.name === "temp_id_seq"));
  const fk = out.edges.filter((e) => e.type === "SQL_REFERENCES");
  assert.deepEqual(fk.map((e) => [e.toId, e.reason]), [["sqltable:conversations", "unresolved sql token: fk notes.conversation_id fk_notes_conv (EF)"]]);
  const maps = out.edges.filter((e) => e.type === "EF_MAPS").map((e) => e.toId);
  assert.ok(maps.includes("efentity:App.Domain.Conversation") && maps.includes("efprop:App.Domain.Assignment#HandledBy"));
  // Not-seen constructs are gaps, never silent drops.
  assert.deepEqual(out.symbols.filter((s) => s.kind === "sql_gap").map((s) => s.name).sort(), ["gap: HasDiscriminator App.Domain.Note", "gap: OwnsMany App.Domain.Conversation"]);
  assert.ok(out.edges.every((e) => e.type !== "EF_MAPS" || e.confidence === 0.5), "tokens until the post-phase binds them");
});

test("release L3: migrations, Designer.cs and a ModelSnapshot without [DbContext] define nothing", () => {
  const designer = SNAPSHOT.replace("[DbContext(typeof(AppDbContext))]", "[DbContext(typeof(AppDbContext))]\n    [Migration(\"20260101_X\")]")
    .replace("partial class AppDbContextModelSnapshot : ModelSnapshot", "partial class X")
    .replace("protected override void BuildModel", "protected override void BuildTargetModel");
  assert.equal(sql(extract(designer, "src/Migrations/20260101_X.Designer.cs")).length, 0, "Designer.cs: a per-migration snapshot, not a definition");
  const migration = `namespace M { public partial class X : Migration { protected override void Up(MigrationBuilder migrationBuilder) {
    migrationBuilder.CreateTable(name: "conversations", columns: table => new { id = table.Column<Guid>(type: "uuid", nullable: false) });
  } } }`;
  assert.equal(sql(extract(migration, "src/Migrations/20260101_X.cs")).length, 0, "a migration is history");
  const noContext = SNAPSHOT.replace("[DbContext(typeof(AppDbContext))]", "");
  assert.equal(sql(extract(noContext, "src/Migrations/AppDbContextModelSnapshot.cs")).length, 0, "no [DbContext]: not a model snapshot");
});
